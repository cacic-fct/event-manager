import generatorHelper from '@prisma/generator-helper';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

// Generation receives the full DMMF, including fields omitted by Prisma's runtime.
generatorHelper.generatorHandler({
  onManifest() {
    return {
      prettyName: 'Audience relation metadata',
      defaultOutput: '../../src/app/audiences/audience-relations.generated.ts',
    };
  },
  onGenerate({ dmmf, generator }) {
    const target = generator.output?.value;
    if (!target) {
      throw new Error('Audience relation metadata requires an output path.');
    }
    const metadata = Object.fromEntries(
      dmmf.datamodel.models.map((model) => [
        model.name,
        model.fields
          .filter((field) => field.kind === 'object')
          .map((field) => ({
            name: field.name,
            type: field.type,
            isList: field.isList,
            isRequired: field.isRequired,
            ownsRelation: field.relationFromFields.length > 0,
          })),
      ]),
    );
    const output = `// Generated by prisma generate (audienceRelations). Do not edit by hand.\nexport const AUDIENCE_RELATIONS = ${JSON.stringify(metadata, null, 2)} as const;\n`;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, output);
  },
});
