import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

// Prisma 7's public runtime DMMF omits cardinality and foreign-key ownership.
// Generate this small security metadata table from the checked-in Prisma schema.
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const schemaDirectory = join(root, 'apps/backend/prisma/schema');
const schema = readdirSync(schemaDirectory)
  .filter((file) => file.endsWith('.prisma'))
  .sort()
  .map((file) => readFileSync(join(schemaDirectory, file), 'utf8'))
  .join('\n');
const models = [...schema.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)];
const names = new Set(models.map((match) => match[1]));
const metadata = Object.fromEntries(
  models.map(([, name, body]) => {
    const relations = [];
    for (const line of body.split('\n')) {
      const field = line.match(/^\s*(\w+)\s+(\w+)(\[\]|\?)?(?:\s+(.*))?$/);
      if (!field || !names.has(field[2])) {
        continue;
      }
      const [, fieldName, type, cardinality, attributes = ''] = field;
      if (attributes.includes('@relation(') && !attributes.includes(')')) {
        throw new Error(`Multiline relation ${name}.${fieldName} needs generator support.`);
      }
      relations.push({
        name: fieldName,
        type,
        isList: cardinality === '[]',
        isRequired: cardinality !== '?',
        ownsRelation: /fields:\s*\[/.test(attributes),
      });
    }
    return [name, relations];
  }),
);
const output = `// Generated by tools/generate-audience-relations.mjs. Do not edit by hand.\nexport const AUDIENCE_RELATIONS = ${JSON.stringify(metadata, null, 2)} as const;\n`;
const target = join(root, 'apps/backend/src/app/audiences/audience-relations.generated.ts');
if (process.argv.includes('--check')) {
  // Node's native TypeScript support loads the data independently of formatting.
  const { AUDIENCE_RELATIONS } = await import(pathToFileURL(target).href);
  if (JSON.stringify(AUDIENCE_RELATIONS) !== JSON.stringify(metadata)) {
    throw new Error(
      'Audience relation metadata is stale. Run node tools/generate-audience-relations.mjs after changing Prisma relations.',
    );
  }
} else {
  writeFileSync(target, output);
}
